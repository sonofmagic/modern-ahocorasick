import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'

// Pinned official source: https://www.unicode.org/Public/17.0.0/ucd/CaseFolding.txt
const source = readFileSync(new URL('../packages/modern-ahocorasick/test/fixtures/CaseFolding-17.0.0.txt', import.meta.url), 'utf8')
assert.equal(createHash('sha256').update(source).digest('hex'), 'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183')
const entries = []
for (const line of source.split('\n')) {
  const [code, status, mapping] = line.split('#')[0].split(';').map(part => part.trim())
  if (status === 'C' || status === 'F') {
    entries.push(`${code}:${mapping.replaceAll(' ', ',')}`)
  }
}
const lines = []
for (let index = 0; index < entries.length; index += 12) {
  lines.push(`  '${entries.slice(index, index + 12).join(';')}',`)
}
writeFileSync(new URL('../packages/modern-ahocorasick/src/case-folding.ts', import.meta.url), `// Generated by scripts/generate-case-folding.mjs from Unicode 17.0.0.
// Copyright © 2025 Unicode, Inc. See UNICODE-LICENSE.txt (Unicode License V3).
const encoded = [
${lines.join('\n')}
].join(';')

let mappings: Map<number, string> | undefined

export function caseFold(text: string, turkic: boolean): string {
  mappings ??= new Map(encoded.split(';').map((entry) => {
    const [code, target] = entry.split(':')
    return [Number.parseInt(code, 16), String.fromCodePoint(...target.split(',').map(value => Number.parseInt(value, 16)))]
  }))
  let result = ''
  for (const character of text) {
    const code = character.codePointAt(0)!
    result += turkic && code === 0x49 ? '\\u0131' : turkic && code === 0x130 ? 'i' : mappings.get(code) ?? character
  }
  return result
}
`)
